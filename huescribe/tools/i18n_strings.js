// Huescribe translation keys: collect them from the code, and build the language files.
//
//   node tools/i18n_strings.js extract            -> locales/source.json  [{id, text, plural?, files, context}]
//   node tools/i18n_strings.js build              -> locales/<code>.js from locales/translations/<code>.json
//   node tools/i18n_strings.js check              -> lists t()/tn() calls whose key is not a string literal
//
// Keys are the English text in t('…'), tn(n, '…', '…') and tk('…') calls (string literals or backtick templates
// without ${}). For tn the "other" form is the key; translators give plural forms for languages that need them.
// Translation files (locales/translations/<code>.json) map id -> text, or id -> {one, few, many, other…} for plurals.
/* eslint-disable no-console */
const fs = require('fs');
const path = require('path');
const acorn = require('/tmp/jsparse/node_modules/acorn');
const walk = require('/tmp/jsparse/node_modules/acorn-walk');

const ROOT = path.join(__dirname, '..');
const FILES = ['panel.js', 'picker.js', 'prompts.js', 'analyzer.js', 'motion.js', 'adjust.js', 'recorder.js', 'background.js', 'welcome.js'];
const LOCALES = path.join(ROOT, 'locales');
const CODES = ['es', 'pt', 'fr', 'de', 'it', 'tr', 'id', 'vi', 'ru', 'ar', 'hi', 'zh', 'ja', 'ko'];
const id = (s) => require('crypto').createHash('sha1').update(s).digest('hex').slice(0, 10);

function literal(node) {
  if (!node) return null;
  if (node.type === 'Literal' && typeof node.value === 'string') return node.value;
  if (node.type === 'TemplateLiteral' && node.expressions.length === 0) return node.quasis[0].value.cooked;
  return null;
}

function calls(file) {
  const src = fs.readFileSync(path.join(ROOT, file), 'utf8');
  const ast = acorn.parse(src, { ecmaVersion: 'latest', sourceType: 'script', locations: true, allowHashBang: true });
  const out = [];
  walk.full(ast, (n) => {
    if (n.type !== 'CallExpression') return;
    const name = n.callee.type === 'Identifier' ? n.callee.name
      : n.callee.type === 'MemberExpression' && !n.callee.computed ? n.callee.property.name : null;
    if (!['t', 'tn', 'tk'].includes(name)) return;
    const line = n.loc.start.line;
    const ctx = src.split('\n')[line - 1].trim().slice(0, 160);
    if (name === 'tn') out.push({ kind: 'tn', one: literal(n.arguments[1]), other: literal(n.arguments[2]), line, ctx, file });
    else out.push({ kind: name, text: literal(n.arguments[0]), line, ctx, file });
  });
  return out;
}

function extract() {
  const byText = new Map();
  for (const f of FILES) {
    for (const c of calls(f)) {
      const key = c.kind === 'tn' ? c.other : c.text;
      if (key == null) continue;
      const e = byText.get(key) || { id: id(key), text: key, files: [], context: [] };
      if (c.kind === 'tn') e.plural = { one: c.one, other: c.other };
      if (!e.files.includes(c.file)) e.files.push(c.file);
      if (e.context.length < 2) e.context.push(`${c.file}:${c.line}  ${c.ctx}`);
      byText.set(key, e);
    }
  }
  const items = [...byText.values()];
  fs.mkdirSync(LOCALES, { recursive: true });
  fs.writeFileSync(path.join(LOCALES, 'source.json'), JSON.stringify(items, null, 1));
  const words = items.reduce((a, e) => a + e.text.split(/\s+/).length, 0);
  console.log(`${items.length} keys, ${words} words, ${items.filter((e) => e.plural).length} plurals`);
}

function check() {
  let bad = 0;
  for (const f of FILES) {
    for (const c of calls(f)) {
      const ok = c.kind === 'tn' ? c.one != null && c.other != null : c.text != null;
      if (!ok && !(c.kind === 't' && /\bt\((\w+(\.\w+|\[[^\]]+\])*)[,)]/.test(c.ctx))) { bad++; console.log(`non-literal ${c.kind}() ${c.file}:${c.line}  ${c.ctx}`); }
    }
  }
  console.log(bad ? `${bad} calls need a literal key` : 'all keys are literals (t(variable) calls rely on tk() at definition)');
}

function build() {
  const source = JSON.parse(fs.readFileSync(path.join(LOCALES, 'source.json'), 'utf8'));
  for (const code of CODES) {
    const file = path.join(LOCALES, 'translations', `${code}.json`);
    if (!fs.existsSync(file)) { console.log(`${code}: no translations yet`); continue; }
    const tr = JSON.parse(fs.readFileSync(file, 'utf8'));
    const cat = {};
    let missing = 0;
    for (const e of source) {
      const v = tr[e.id];
      if (v == null || v === '') { missing++; continue; }
      cat[e.text] = v;
    }
    const js = `/* Huescribe: ${code} translations. Generated by tools/i18n_strings.js build from locales/translations/${code}.json; edit that file, not this one. */\n`
      + `(globalThis.HS_L10N = globalThis.HS_L10N || {})[${JSON.stringify(code)}] = ${JSON.stringify(cat)};\n`;
    fs.writeFileSync(path.join(LOCALES, `${code}.js`), js);
    console.log(`${code}: ${source.length - missing}/${source.length}`);
  }
}

({ extract, build, check })[process.argv[2]]();
